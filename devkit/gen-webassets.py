#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 web/ 下的前端增强资源转成可编译进 dylib 的 C 字符串头。

用法：
    python3 devkit/gen-webassets.py <web_dir> <output_header>

为什么不用「运行时读 bundle 文件」：
    不改 App 包内 GCDWebUploader.bundle 的任何文件 —— 那会破坏代码签名。
    增强层由 Tweak.xm hook HTML 模板渲染、把 CSS/JS 追加到 epilogue 变量里下发，
    所以资源必须作为常量编进 dylib。

硬判据（不能是永远通过的检查）：
    1. 源文件必须存在、非空、大小在上限内；
    2. 内容里不得出现会截断 HTML 的 </script、以及模板变量形状 %key%；
    3. 生成后把头文件里的 C 字面量**反向解码**回字节，与源文件 sha256 逐一比对，
       不一致直接以非零码退出（编码/转义 bug 会在这里被抓到，不会流到真机）。
"""
import hashlib
import os
import re
import sys

MAX_BYTES = 256 * 1024
DANGEROUS = [
    (re.compile(rb"</script", re.I), "含 </script 字面量，会提前截断内联 script"),
    (re.compile(rb"%(?:device|title|header|prologue|epilogue|footer)%", re.I),
     "含模板变量形状，会被 GCDWebServer 的二次替换改写"),
]

# ASCII 里直接放行可打印字符，但排除会与 C 转义 / trigraph 冲突的三个
SAFE = set(range(0x20, 0x7f)) - {ord("\\"), ord('"'), ord("?")}


def sha(b):
    return hashlib.sha256(b).hexdigest()


def read_source(path):
    if not os.path.isfile(path):
        raise SystemExit("::error::缺少前端资源 %s" % path)
    with open(path, "rb") as f:
        raw = f.read()
    if not raw:
        raise SystemExit("::error::前端资源为空 %s" % path)
    if len(raw) > MAX_BYTES:
        raise SystemExit("::error::前端资源过大 %s (%d > %d)" % (path, len(raw), MAX_BYTES))
    for rx, why in DANGEROUS:
        m = rx.search(raw)
        if m:
            raise SystemExit("::error::%s 第 %d 字节：%s" % (path, m.start(), why))
    return raw


def c_escape(chunk):
    """按 UTF-8 字节转义；非安全字节用 3 位八进制（固定长度，不会吞掉后续字符）。"""
    out = []
    for b in chunk:
        if b in SAFE:
            out.append(chr(b))
        elif b == ord("\\"):
            out.append("\\\\")
        elif b == ord('"'):
            out.append('\\"')
        else:
            out.append("\\%03o" % b)
    return "".join(out)


def emit_array(name, raw):
    lines = ['static const char %s[] =' % name]
    for chunk in raw.splitlines(keepends=True):
        lines.append('    "%s"' % c_escape(chunk))
    lines.append('    ;')
    return "\n".join(lines)


def unescape(s):
    """把生成的一个 C 字符串字面量内容还原成字节。"""
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c != "\\":
            out.append(ord(c))
            i += 1
            continue
        nxt = s[i + 1] if i + 1 < len(s) else ""
        if nxt in ("0", "1", "2", "3", "4", "5", "6", "7"):
            out.append(int(s[i + 1:i + 4], 8) & 0xFF)
            i += 4
        elif nxt == "\\":
            out.append(0x5C)
            i += 2
        elif nxt == '"':
            out.append(0x22)
            i += 2
        else:
            raise ValueError("未知 C 转义 \\%s" % nxt)
    return bytes(out)


def decode_array(text, name):
    """从头文件里取出指定数组的所有字面量并解码，返回字节串。"""
    m = re.search(r"static const char %s\[\] =(.*?)\n    ;" % re.escape(name),
                  text, re.S)
    if not m:
        raise ValueError("找不到数组 %s" % name)
    literals = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
    if not literals:
        raise ValueError("数组 %s 里没有字符串字面量" % name)
    return b"".join(unescape(x) for x in literals)


def main():
    if len(sys.argv) != 3:
        raise SystemExit("用法: gen-webassets.py <web_dir> <output_header>")
    web_dir, out_path = sys.argv[1], sys.argv[2]

    js = read_source(os.path.join(web_dir, "oka-wifi.js"))
    css = read_source(os.path.join(web_dir, "oka-wifi.css"))

    header = "\n".join([
        "#ifndef OKA_WEB_ASSETS_H",
        "#define OKA_WEB_ASSETS_H",
        "// Generated by devkit/gen-webassets.py -- DO NOT EDIT.",
        "// web/oka-wifi.js   sha256=" + sha(js),
        "// web/oka-wifi.css  sha256=" + sha(css),
        "// ASCII-only header; payload bytes are emitted as C string literals.",
        "",
        emit_array("kOkaWebJS", js),
        "",
        emit_array("kOkaWebCSS", css),
        "",
        "#endif /* OKA_WEB_ASSETS_H */",
        "",
    ])

    # 反向解码自检：读回的就是即将被编译的字节，不是源码本身
    for name, raw in (("kOkaWebJS", js), ("kOkaWebCSS", css)):
        decoded = decode_array(header, name)
        if decoded != raw:
            raise SystemExit("::error::%s 往返解码不一致：源 %d 字节 / 解码 %d 字节，sha=%s vs %s"
                             % (name, len(raw), len(decoded), sha(raw), sha(decoded)))

    out_dir = os.path.dirname(os.path.abspath(out_path))
    if out_dir and not os.path.isdir(out_dir):
        os.makedirs(out_dir, exist_ok=True)
    with open(out_path, "w", encoding="ascii", newline="\n") as f:
        f.write(header)

    # 落盘后再读一次磁盘内容做同样的解码断言（防止写文件环节丢字节/改行尾）
    with open(out_path, "rb") as f:
        on_disk = f.read().decode("ascii")
    for name, raw in (("kOkaWebJS", js), ("kOkaWebCSS", css)):
        if decode_array(on_disk, name) != raw:
            raise SystemExit("::error::落盘后 %s 解码不一致" % name)

    print("✓ 生成 %s (%d 字节)" % (out_path, len(header.encode("ascii"))))
    print("  kOkaWebJS   %6d 字节  sha256=%s" % (len(js), sha(js)))
    print("  kOkaWebCSS  %6d 字节  sha256=%s" % (len(css), sha(css)))
    print("✓ 往返解码自检通过（含落盘复读）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
